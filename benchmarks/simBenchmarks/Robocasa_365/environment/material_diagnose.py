"""Independent XML material reference; no benchmark reset, physics or model call.

Run each condition in a fresh process. The candidate renders literal (-1,.5,2)
with v3. A separately authored legal (0,.5,1) XML is rendered with lifecycle-only
v2 and its native material entrypoint. Compare all three raw RGB hashes; two
individually passing reports alone do not establish reference equivalence.
"""

from __future__ import annotations

import argparse
import gc
import hashlib
import json
import os
import traceback
import types
from pathlib import Path

from benchkit.artifacts import atomic_write_json
from .render_lifecycle import MATERIAL_TRACK, TRACK, install

# Deliberately independent literals: the legal reference is not generated by
# the conversion under test, XML rewriting, or the candidate's rendered scene.
CANDIDATE = '''<mujoco><visual><global offwidth="256" offheight="256"/></visual>
<asset><material name="negative" shininess="-1" specular=".8" rgba=".8 .1 .1 1"/>
<material name="legal" shininess=".5" specular=".8" rgba=".1 .8 .1 1"/>
<material name="positive" shininess="2" specular=".8" rgba=".1 .1 .8 1"/></asset>
<worldbody><light pos="0 -1 3"/><geom type="plane" size="2 2 .1" rgba=".3 .3 .3 1"/>
<geom type="sphere" pos="-.45 0 .22" size=".22" material="negative"/>
<geom type="sphere" pos="0 0 .22" size=".22" material="legal"/>
<geom type="sphere" pos=".45 0 .22" size=".22" material="positive"/>
<camera name="front" pos="0 -2 1.5" xyaxes="1 0 0 0 .6 .8"/>
<camera name="side" pos="2 0 1.5" xyaxes="0 1 0 -.6 0 .8"/>
<camera name="top" pos="0 0 3" xyaxes="1 0 0 0 1 0"/>
</worldbody></mujoco>'''

REFERENCE = '''<mujoco><visual><global offwidth="256" offheight="256"/></visual>
<asset><material name="negative" shininess="0" specular=".8" rgba=".8 .1 .1 1"/>
<material name="legal" shininess=".5" specular=".8" rgba=".1 .8 .1 1"/>
<material name="positive" shininess="1" specular=".8" rgba=".1 .1 .8 1"/></asset>
<worldbody><light pos="0 -1 3"/><geom type="plane" size="2 2 .1" rgba=".3 .3 .3 1"/>
<geom type="sphere" pos="-.45 0 .22" size=".22" material="negative"/>
<geom type="sphere" pos="0 0 .22" size=".22" material="legal"/>
<geom type="sphere" pos=".45 0 .22" size=".22" material="positive"/>
<camera name="front" pos="0 -2 1.5" xyaxes="1 0 0 0 .6 .8"/>
<camera name="side" pos="2 0 1.5" xyaxes="0 1 0 -.6 0 .8"/>
<camera name="top" pos="0 0 3" xyaxes="1 0 0 0 1 0"/>
</worldbody></mujoco>'''


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--gpu", type=int, required=True)
    parser.add_argument("--condition", choices=("candidate", "legal-reference"), required=True)
    args = parser.parse_args(argv)
    if args.gpu < 0:
        parser.error("gpu must be nonnegative")
    args.output = args.output.absolute()
    args.output.mkdir(parents=True, exist_ok=False)
    previous_directory = Path.cwd()
    report = {
        "schema_version": "starvla-rsi.robocasa365.material-reference-diagnostic/v1",
        "kind": "independent_xml_material_render_reference", "condition": args.condition,
        "capability_evaluation": False, "benchmark_resets": 0, "physics_steps": 0,
        "controls": 0, "model_calls": 0, "gpu": args.gpu,
        "diagnostic_source_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "errors": [], "frames": [], "status": "running",
    }
    candidate = args.condition == "candidate"
    xml = CANDIDATE if candidate else REFERENCE
    expected = [-1., .5, 2.] if candidate else [0., .5, 1.]
    report["input_xml_sha256"] = hashlib.sha256(xml.encode()).hexdigest()
    guard = sim = renderer = None
    try:
        # Keep native MUJOCO_LOG beside this diagnostic, not in sources. Restore
        # the caller's directory even when an early write/import/preflight fails.
        os.chdir(args.output)
        (args.output / "scene.xml").write_text(xml)
        atomic_write_json(args.output / "report.json", report)
        from ..bench_server.adapter import verify_sources
        sources = verify_sources()
        report["native_sources"] = sources
        guard = install(args.output / "render_lifecycle.json", Path(sources["sources"]["robosuite"]["root"]),
                        track=MATERIAL_TRACK if candidate else TRACK)
        import mujoco
        from PIL import Image
        from robosuite.utils.binding_utils import MjSim, MjRenderContextOffscreen
        report["material_entrypoint_is_native_builtin"] = isinstance(mujoco.mjr_render, types.BuiltinFunctionType)
        if report["material_entrypoint_is_native_builtin"] == candidate:
            raise RuntimeError("candidate/reference material hook separation failed")
        sim = MjSim.from_xml_string(xml)
        model = sim.model._model
        report["model_material_values_before"] = model.mat_shininess.tolist()
        if report["model_material_values_before"] != expected:
            raise RuntimeError("native model differs from independently declared material values")
        compiled_xml_before = sim.model.get_xml()
        renderer = MjRenderContextOffscreen(sim, device_id=args.gpu, max_width=256, max_height=256)
        for camera in ("front", "side", "top"):
            pixels = sim.render(256, 256, camera_name=camera)
            model_values = model.mat_shininess.tolist()
            scene_values = sorted((int(renderer.scn.geoms[i].matid), float(renderer.scn.geoms[i].shininess))
                                  for i in range(renderer.scn.ngeom) if renderer.scn.geoms[i].matid >= 0)
            if (model_values != expected or scene_values != list(enumerate(expected))
                    or sim.model.get_xml() != compiled_xml_before):
                raise RuntimeError("model/XML or expanded scene was not restored after native draw")
            if pixels.shape != (256, 256, 3) or str(pixels.dtype) != "uint8":
                raise RuntimeError("unexpected RGB shape/type")
            path = args.output / f"{camera}.png"
            Image.fromarray(pixels).save(path)
            report["frames"].append({"camera": camera, "rgb_sha256": hashlib.sha256(pixels.tobytes()).hexdigest(),
                                     "png_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                                     "model_material_values_after": model_values,
                                     "scene_material_values_after": scene_values})
        report["model_and_xml_unchanged"] = True
        report["scene_restored_after_every_draw"] = True
        if (candidate and guard.counts["material_geometries_clamped"] != 6
                or not candidate and guard.counts["material_transform_attempts"] != 0):
            raise RuntimeError("unexpected material transformation count")
        report["status"] = "passed"
    except Exception as exc:
        report["status"] = "failed"
        report["errors"].append({"type": type(exc).__name__, "message": str(exc), "traceback": traceback.format_exc()})
    finally:
        renderer = None
        if sim is not None:
            try:
                sim.free()
            except Exception as exc:
                report["status"] = "failed"
                report["errors"].append({"phase": "cleanup", "type": type(exc).__name__, "message": str(exc)})
        sim = None
        gc.collect()
        if guard is not None:
            try:
                guard.finish()
            except Exception as exc:
                report["status"] = "failed"
                report["errors"].append({"phase": "guard_close", "type": type(exc).__name__, "message": str(exc)})
            report["guard_final"] = guard.receipt()
        try:
            atomic_write_json(args.output / "report.json", report)
        finally:
            os.chdir(previous_directory)
    print(json.dumps({"condition": args.condition, "status": report["status"], "output": str(args.output)}), flush=True)
    return 0 if report["status"] == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
